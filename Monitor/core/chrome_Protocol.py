from typing import Protocol, overload, Any, Iterable

class ILocatorProtocol(Protocol):
    driver: Any
    _loc: Any

    @property
    def text(self) -> str: ...
    def click(self) -> None: ...
    def get_attribute(self, name: str) -> str | None: ...

    @property
    def inner_html(self) -> str: ...
    @property
    def outer_html(self) -> str: ...

    @overload
    def __getitem__(self, index: int) -> "ILocatorProtocol": ...
    @overload
    def __getitem__(self, index: slice) -> "ILocatorListProtocol": ...
    def __getitem__(self, index): ...

    def __len__(self) -> int: ...
    def __iter__(self) -> Iterable["ILocatorProtocol"]: ...

class ILocatorListProtocol(Protocol):
    @overload
    def __getitem__(self, index: int) -> ILocatorProtocol: ...
    @overload
    def __getitem__(self, index: slice) -> "ILocatorListProtocol": ...
    def __getitem__(self, index): ...

    def __len__(self) -> int: ...
    def __iter__(self) -> Iterable[ILocatorProtocol]: ...

class PageExProtocol(Protocol):
    _page: Any

    def locator(self, selector: str, **kwargs) -> Any: ...

    def goto(self, url: str) -> None: ...
    def wait_for_url(self, pattern: Any, timeout: int) -> None: ...

    def __getattr__(self, name: str) -> Any: ...

class ChromeProtocol(Protocol):
    page: PageExProtocol
    context: Any
    browser: Any

    def findElement(self, selector: str, base: Any = None) -> ILocatorProtocol | None: ...
    def findElements(self, selector: str, base: Any = None) -> list[ILocatorProtocol]: ...
    def findCells(self, base: Any = None) -> list[ILocatorProtocol]: ...

    def get(self, url: str) -> None: ...
    @property
    def current_url(self) -> str: ...

    def waitFor(self, url: str, delay: int) -> str: ...

    def new_window(self, type_: str = "tab") -> None: ...
    def switch_to_new_window(self) -> None: ...
    def get_back_to_original_window(self) -> None: ...
    def close_window(self) -> None: ...

    def execute_script(self, script: str, *args: Any) -> Any: ...

    def download(self, bouton: ILocatorProtocol) -> str: ...

    def terminate(self) -> None: ...
